-- Shree Mohan Sweets: schema, row level security, checkout functions and image storage.

create table public.categories (
  id smallint primary key,
  name text not null unique
);

create table public.products (
  id bigint generated by default as identity primary key,
  name text not null,
  price numeric(10, 2) not null default 0 check (price >= 0), -- per kg; 0 means price on request
  category_id smallint references public.categories (id) on delete set null,
  image text,
  featured boolean not null default false,
  stock_quantity integer not null default 10 check (stock_quantity >= 0),
  stock_status text not null default 'Available' check (stock_status in ('Available', 'Out of Stock')),
  created_at timestamptz not null default now()
);
create index products_category_id_idx on public.products (category_id);

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  name text not null default '',
  phone text not null default '',
  created_at timestamptz not null default now()
);

create table public.orders (
  id bigint generated by default as identity primary key,
  customer_id uuid references public.profiles (id) on delete set null,
  customer_name text not null,
  phone text not null,
  address text not null,
  payment_method text not null check (payment_method in ('UPI', 'Cash on Delivery')),
  total_amount numeric(10, 2) not null,
  status text not null default 'Pending' check (status in ('Pending', 'Confirmed', 'Delivered')),
  stock_applied boolean not null default false,
  access_token uuid not null default gen_random_uuid() unique, -- the private link for guest orders
  created_at timestamptz not null default now()
);
create index orders_customer_id_idx on public.orders (customer_id);

create table public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders (id) on delete cascade,
  product_id bigint not null references public.products (id) on delete restrict,
  quantity integer not null check (quantity > 0),
  weight text,
  price numeric(10, 2) not null
);
create index order_items_order_id_idx on public.order_items (order_id);
create index order_items_product_id_idx on public.order_items (product_id);

create table public.payments (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders (id) on delete cascade,
  amount numeric(10, 2) not null,
  method text not null,
  status text not null default 'Pending' check (status in ('Pending', 'Completed')),
  created_at timestamptz not null default now()
);
create index payments_order_id_idx on public.payments (order_id);

create table public.offers (
  id bigint generated by default as identity primary key,
  description text not null,
  discount numeric(5, 2) not null default 0,
  start_date date not null default current_date,
  end_date date not null default current_date,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.reviews (
  id bigint generated by default as identity primary key,
  customer_name text not null,
  rating smallint not null check (rating between 1 and 5),
  review_text text not null,
  created_at timestamptz not null default now()
);

create table public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  message text not null,
  created_at timestamptz not null default now()
);

-- Admin rights live in app_metadata, which users cannot edit themselves.
create function public.is_admin()
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
  select coalesce((select auth.jwt()) -> 'app_metadata' ->> 'role' = 'admin', false);
$$;

