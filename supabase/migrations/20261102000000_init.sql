-- New accounts get a profile. Metadata is user-supplied, so it is only used for display.
create schema if not exists private;

create function private.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, name, phone)
  values (
    new.id,
    left(coalesce(new.raw_user_meta_data ->> 'name', ''), 150),
    left(coalesce(new.raw_user_meta_data ->> 'phone', ''), 20)
  );
  return new;
end;
$$;
revoke all on function private.handle_new_user() from public, anon, authenticated;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function private.handle_new_user();

-- Checkout is open to guests but tables are not, so these three functions are the only
-- way in. Security definer is deliberate. Each one validates its own input, and
-- place_order reads prices itself so a browser can never set what it pays.
-- Keep the weight and delivery rules in step with src/lib/pricing.ts.
create function public.place_order(
  p_customer_name text,
  p_phone text,
  p_address text,
  p_payment_method text,
  p_lines jsonb
)
returns table (order_id bigint, access_token uuid)
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_line jsonb;
  v_product record;
  v_quantity integer;
  v_weight text;
  v_unit numeric(10, 2);
  v_subtotal numeric(10, 2) := 0;
  v_total numeric(10, 2);
  v_order_id bigint;
  v_token uuid;
begin
  if char_length(trim(p_customer_name)) not between 1 and 150 then
    raise exception 'Please enter your name.' using errcode = 'P0001';
  end if;
  if p_phone !~ '^[0-9]{10}$' then
    raise exception 'Please enter a valid 10-digit phone number.' using errcode = 'P0001';
  end if;
  if char_length(trim(p_address)) not between 1 and 1000 then
    raise exception 'Please enter your delivery address.' using errcode = 'P0001';
  end if;
  if p_payment_method not in ('UPI', 'Cash on Delivery') then
    raise exception 'Please choose a payment method.' using errcode = 'P0001';
  end if;
  if jsonb_typeof(p_lines) is distinct from 'array' or jsonb_array_length(p_lines) not between 1 and 100 then
    raise exception 'Your cart is empty.' using errcode = 'P0001';
  end if;

  insert into public.orders (customer_id, customer_name, phone, address, payment_method, total_amount)
  values ((select auth.uid()), trim(p_customer_name), p_phone, trim(p_address), p_payment_method, 0)
  returning id, orders.access_token into v_order_id, v_token;

  for v_line in select * from jsonb_array_elements(p_lines) loop
    v_quantity := (v_line ->> 'quantity')::integer;
    v_weight := v_line ->> 'weight';
    if v_quantity is null or v_quantity not between 1 and 50 or v_weight not in ('250g', '500g', '1kg') then
      raise exception 'Your cart could not be read. Please try again.' using errcode = 'P0001';
    end if;

    select p.id, p.name, p.price, p.stock_status into v_product
    from public.products p where p.id = (v_line ->> 'productId')::bigint;
    if not found or v_product.price <= 0 or v_product.stock_status <> 'Available' then
      raise exception '% is not available to order online right now.', coalesce(v_product.name, 'An item')
        using errcode = 'P0001';
    end if;

    v_unit := round(v_product.price * case v_weight when '250g' then 0.25 when '500g' then 0.5 else 1 end, 2);
    v_subtotal := v_subtotal + v_unit * v_quantity;
    insert into public.order_items (order_id, product_id, quantity, weight, price)
    values (v_order_id, v_product.id, v_quantity, v_weight, v_unit);
  end loop;

  v_total := v_subtotal + case when v_subtotal >= 1000 then 0 else 40 end;
  update public.orders set total_amount = v_total where id = v_order_id;
  insert into public.payments (order_id, amount, method) values (v_order_id, v_total, p_payment_method);

  return query select v_order_id, v_token;
end;
$$;

-- Holding the unguessable token is what proves access to an order.
create function public.get_order(p_order_id bigint, p_token uuid)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'id', o.id,
    'customer_name', o.customer_name,
    'phone', o.phone,
    'address', o.address,
    'payment_method', o.payment_method,
    'total_amount', o.total_amount,
    'status', o.status,
    'created_at', o.created_at,
    'access_token', o.access_token,
    'bill_no', (select count(*) from public.orders b where b.id <= o.id),
    'items', coalesce((
      select jsonb_agg(jsonb_build_object(
        'id', i.id, 'name', p.name, 'quantity', i.quantity, 'weight', i.weight, 'price', i.price
      ) order by i.id)
      from public.order_items i join public.products p on p.id = i.product_id
      where i.order_id = o.id
    ), '[]'::jsonb)
  )
  from public.orders o
  where o.id = p_order_id and o.access_token = p_token;
$$;

create function public.track_order(p_order_id bigint, p_phone text)
returns table (id bigint, status text, total_amount numeric, created_at timestamptz, access_token uuid)
language sql
stable
security definer
set search_path = ''
as $$
  select o.id, o.status, o.total_amount, o.created_at, o.access_token
  from public.orders o
  where o.id = p_order_id and o.phone = p_phone;
$$;

-- Stock leaves the shelf once, the first time an order is accepted.
create function public.update_order_status(p_order_id bigint, p_status text)
returns void
language plpgsql
security invoker
set search_path = ''
as $$
declare
  v_applied boolean;
begin
  if not public.is_admin() then
    raise exception 'Not allowed.' using errcode = '42501';
  end if;
  select o.stock_applied into v_applied from public.orders o where o.id = p_order_id for update;
  if not found then
    return;
  end if;
  update public.orders set status = p_status where id = p_order_id;
  if p_status <> 'Pending' and not v_applied then
    update public.products p
    set stock_quantity = greatest(p.stock_quantity - i.quantity, 0)
    from public.order_items i
    where i.product_id = p.id and i.order_id = p_order_id;
    update public.orders set stock_applied = true where id = p_order_id;
  end if;
end;
$$;

