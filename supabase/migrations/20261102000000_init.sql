-- Admin dashboard totals.
create function public.dashboard_stats()
returns jsonb
language plpgsql
stable
security invoker
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception 'Not allowed.' using errcode = '42501';
  end if;
  return jsonb_build_object(
    'products', (select count(*) from public.products),
    'unpriced', (select count(*) from public.products where price = 0),
    'orders', (select count(*) from public.orders),
    'pending', (select count(*) from public.orders where status = 'Pending'),
    'revenue', (select coalesce(sum(total_amount), 0) from public.orders)
  );
end;
$$;

revoke all on function public.dashboard_stats() from public, anon;
grant execute on function public.dashboard_stats() to authenticated;
revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;
